import { chromium } from "playwright"
const browser = await chromium.launch({ channel: "chrome" })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto("http://localhost:5199/")
await page.locator(".loading .enter").click({ timeout: 90000 })
await page.waitForTimeout(1500)
const box = await page.locator(".paper-sheet").first().boundingBox()
await page.mouse.dblclick(box.x + box.width / 2, box.y + box.height / 2)
await page.waitForTimeout(1500)
await page.screenshot({ path: "shots/p1.png" })
await page.keyboard.press("ArrowRight"); await page.waitForTimeout(1800)
await page.screenshot({ path: "shots/p2.png" })
await browser.close()
