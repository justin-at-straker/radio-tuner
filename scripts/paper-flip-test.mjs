// The newspaper: pick it up, flick through to the letters page, and try the form.
import { chromium } from "playwright"
const browser = await chromium.launch({ channel: "chrome" })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on("pageerror", (e) => console.log("pageerror:", e.message))
await page.goto("http://localhost:5199/")
await page.locator(".loading .enter").click({ timeout: 90000 })
await page.waitForTimeout(2000)
const sheet = page.locator(".paper-sheet").first()
const box = await sheet.boundingBox()
await page.mouse.dblclick(box.x + box.width / 2, box.y + box.height / 2)
await page.waitForTimeout(1500)
await page.screenshot({ path: "shots/12-paper-front.png" })
await page.getByRole("button", { name: "Turn to page 2" }).click()
await page.waitForTimeout(350)
await page.screenshot({ path: "shots/13-paper-turning.png" })
await page.waitForTimeout(900)
await page.screenshot({ path: "shots/14-paper-p2.png" })
await page.keyboard.press("ArrowRight")
await page.waitForTimeout(1100)
await page.keyboard.press("ArrowRight")
await page.waitForTimeout(1300)
await page.screenshot({ path: "shots/15-paper-letters.png" })
console.log("announced:", await page.locator(".visually-hidden[role=status]").innerText())
// the form, through the page as a person would
await page.getByLabel("Your name").fill("Test Reader")
await page.getByLabel("Your email").fill("reader@example.com")
await page.getByLabel("Your letter").fill("Lovely radio. Tell me more about the Model Factory.")
await page.getByRole("button", { name: "Post the letter" }).click()
await page.waitForTimeout(1000)
console.log("form status:", await page.locator(".sent-status").innerText())
await page.screenshot({ path: "shots/16-paper-sent.png" })
// the agent view of the newspaper's controls
console.log("agent sees:", JSON.stringify(await page.evaluate(() => window.agent.snapshot().filter((c) => !c.offPage).map((c) => `${c.component}:${c.label}${c.confirm ? " [confirm]" : ""}`))))
await browser.close()
