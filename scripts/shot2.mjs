import { chromium } from "playwright"
const browser = await chromium.launch({ channel: "chrome", args: ["--autoplay-policy=no-user-gesture-required"] })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
page.on("pageerror", (e) => console.log("pageerror:", e.message))
await page.goto("http://localhost:5199/")
await page.waitForTimeout(1500)
await page.locator(".key", { hasText: "MW" }).click()
// keyboard on the tuning knob: focus the real input, nudge it
await page.locator('input[aria-label="Tuning"]').focus()
for (let i = 0; i < 5; i++) await page.keyboard.press("ArrowUp")
console.log("tuning value:", await page.locator('input[aria-label="Tuning"]').inputValue())
await page.waitForTimeout(1500)
await page.screenshot({ path: "shots/3-front.png" })
// turn it round: drag on empty canvas
await page.mouse.move(150, 150)
await page.mouse.down()
for (let i = 1; i <= 20; i++) await page.mouse.move(150 + i * 19.6, 150)
await page.waitForTimeout(120)
await page.mouse.up()
await page.waitForTimeout(2500)
await page.screenshot({ path: "shots/4-back.png" })
console.log("label box:", await page.locator(".label").boundingBox())
console.log("dial box (should be gone/offscreen):", await page.locator(".dial").boundingBox())
await browser.close()
