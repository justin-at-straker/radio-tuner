import { chromium } from "playwright"
const browser = await chromium.launch({ channel: "chrome", args: ["--autoplay-policy=no-user-gesture-required"] })
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
page.on("pageerror", (e) => console.log("pageerror:", e.message))
page.on("console", (m) => m.type() === "error" && !m.text().includes("404") && console.log("console:", m.text()))
await page.goto("http://localhost:5199/")
await page.waitForTimeout(2500)
console.log("notice:", await page.locator(".notice").count())
await page.locator(".key", { hasText: "MW" }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: "shots/5-rest.png" })
// double-click the radio's grille (cabinet, not a panel): find it from the dial's box
const dial = await page.locator(".dial").boundingBox()
await page.mouse.dblclick(dial.x + dial.width / 2, dial.y - dial.height * 0.8)
await page.waitForTimeout(1200)
console.log("hud:", await page.locator(".hud").innerText())
await page.screenshot({ path: "shots/6-focus.png" })
await page.mouse.dblclick(60, 120)
await page.waitForTimeout(1200)
console.log("hud after:", (await page.locator(".hud").innerText()).split("\n")[0])
await browser.close()
