// The newspaper: resting on the table, then picked up to read.
import { chromium } from "playwright"
const browser = await chromium.launch({ channel: "chrome" })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on("pageerror", (e) => console.log("pageerror:", e.message))
await page.goto("http://localhost:5199/")
await page.locator(".loading .enter").click({ timeout: 90000 })
await page.waitForTimeout(2500)
await page.screenshot({ path: "shots/10-paper-rest.png" })
const box = await page.locator(".paper-sheet").boundingBox()
console.log("paper on table, on-screen box:", box && Object.fromEntries(Object.entries(box).map(([k, v]) => [k, Math.round(v)])))
await page.mouse.dblclick(box.x + box.width / 2, box.y + box.height / 2)
await page.waitForTimeout(1500)
console.log("hud:", (await page.locator(".hud").innerText()).split("\n")[0])
await page.screenshot({ path: "shots/11-paper-held.png" })
const link = page.locator(".enquiries a", { hasText: "github" })
const lb = await link.boundingBox()
const popup = page.waitForEvent("popup", { timeout: 5000 }).catch(() => null)
await page.mouse.click(lb.x + lb.width / 2, lb.y + lb.height / 2)
console.log("github link in paper ->", (await popup)?.url() ?? "no popup")
await page.keyboard.press("Escape")
await page.waitForTimeout(1200)
console.log("after Escape:", (await page.locator(".hud").innerText()).split("\n")[0])
await browser.close()
